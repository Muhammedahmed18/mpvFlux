package app.marlboroadvance.mpvex.ui.mediainfo

import android.content.Context
import app.marlboroadvance.mpvex.R
import app.marlboroadvance.mpvex.utils.media.HardwareDecoderSupport
import app.marlboroadvance.mpvex.utils.media.MediaInfoOps

/** What the media info screen shows. */
internal sealed interface MediaInfoUiState {
  data object Loading : MediaInfoUiState

  data class Error(val message: String?) : MediaInfoUiState

  data class Loaded(val details: MediaInfoDetails) : MediaInfoUiState
}

/** Everything the screen needs, prepared once in the ViewModel (off the main thread). */
internal data class MediaInfoDetails(
  val fileName: String,
  val title: String,
  val subtitle: String,
  val isAudioOnly: Boolean,
  val badges: List<InfoBadge>,
  val decoder: DecoderVerdict?,
  val videoBlocks: List<VideoBlock>,
  val audioTracks: List<TrackRow>,
  val subtitleTracks: List<TrackRow>,
  val fileFields: List<InfoField>,
  val reportSections: List<ReportSection>,
  val reportText: String,
  val summaryText: String,
)

internal data class InfoBadge(val label: String, val highlighted: Boolean = false)

internal data class InfoField(val label: String, val value: String)

internal data class VideoBlock(val title: String, val fields: List<InfoField>)

internal data class TrackRow(
  val headline: String,
  val supporting: String,
  val title: String?,
  val tags: List<TrackTag>,
  val copyText: String,
)

internal enum class TrackTag { Default, Forced, ImageBased }

internal data class ReportSection(val name: String, val properties: List<InfoField>)

/** Whether this phone can decode the video in hardware (null = couldn't tell). */
internal sealed interface DecoderVerdict {
  data object Hardware : DecoderVerdict

  data class Software(val reason: String) : DecoderVerdict
}

// ── Building the details ────────────────────────────────────────────────────

internal object MediaInfoFormatter {

  fun build(
    context: Context,
    fileName: String,
    info: MediaInfoOps.MediaInfoData,
    inform: String,
  ): MediaInfoDetails {
    val general = info.general
    val video = info.videoStreams.firstOrNull()

    val title = general.title.clean() ?: fileName.substringBeforeLast('.').ifBlank { fileName }
    val subtitle =
      listOfNotNull(
        general.duration.clean()?.let(::shortDuration),
        general.fileSize.clean(),
        general.format.clean(),
      ).joinToString(" · ")

    val reportText =
      buildString {
        appendLine("=".repeat(60))
        appendLine("MEDIA INFO - $fileName")
        appendLine("=".repeat(60))
        appendLine()
        append(inform.trimEnd())
        appendLine()
        appendLine()
        appendLine("=".repeat(60))
        appendLine("Generated by mpvFlux using MediaInfoLib")
        appendLine("=".repeat(60))
      }

    val audioTracks = info.audioStreams.map { audioRow(context, it) }
    val subtitleTracks = info.textStreams.map { subtitleRow(context, it) }

    return MediaInfoDetails(
      fileName = fileName,
      title = title,
      subtitle = subtitle,
      isAudioOnly = info.videoStreams.isEmpty(),
      badges = badges(context, info),
      decoder = video?.let { decoderVerdict(context, it) },
      videoBlocks =
        info.videoStreams.mapIndexed { index, v ->
          VideoBlock(
            title =
              if (info.videoStreams.size > 1) {
                context.getString(R.string.media_info_section_video_n, index + 1)
              } else {
                context.getString(R.string.media_info_section_video)
              },
            fields = videoFields(context, v),
          )
        },
      audioTracks = audioTracks,
      subtitleTracks = subtitleTracks,
      fileFields = fileFields(context, fileName, general),
      reportSections = parseReport(inform),
      reportText = reportText,
      summaryText = summary(context, title, info, audioTracks, subtitleTracks),
    )
  }

  private fun badges(context: Context, info: MediaInfoOps.MediaInfoData): List<InfoBadge> =
    buildList {
      info.videoStreams.firstOrNull()?.let { v ->
        resolutionLabel(digits(v.width), digits(v.height))?.let { add(InfoBadge(it)) }
        hdrLabel(v.hdrFormat)?.let { add(InfoBadge(it, highlighted = true)) }
        if (digits(v.bitDepth) >= 10) add(InfoBadge("${digits(v.bitDepth)}-bit", highlighted = true))
        v.format.clean()?.let { add(InfoBadge(it)) }
      }
      info.audioStreams.firstOrNull()?.let { a ->
        channelLabel(context, a.channels)?.let { add(InfoBadge(it)) }
      }
      if (info.audioStreams.isNotEmpty()) {
        add(InfoBadge(context.getString(R.string.media_info_badge_audio, info.audioStreams.size)))
      }
      if (info.textStreams.isNotEmpty()) {
        add(InfoBadge(context.getString(R.string.media_info_badge_subtitles, info.textStreams.size)))
      }
    }

  private fun videoFields(context: Context, v: MediaInfoOps.VideoStreamInfo): List<InfoField> {
    val width = digits(v.width)
    val height = digits(v.height)
    val resolution =
      if (width > 0 && height > 0) {
        listOfNotNull("$width×$height", v.displayAspectRatio.clean()).joinToString(" · ")
      } else {
        null
      }
    // The tile is labelled "Frame rate", so the "FPS" unit MediaInfo appends is dropped.
    val frameRate =
      v.frameRate.clean()?.replace(FPS_SUFFIX, "")?.trim()?.ifBlank { null }?.let { fps ->
        if (v.frameRateMode.equals("VFR", ignoreCase = true)) {
          "$fps · ${context.getString(R.string.media_info_frame_rate_variable)}"
        } else {
          fps
        }
      }
    val bitDepth = listOfNotNull(v.bitDepth.clean(), v.chromaSubsampling.clean()).joinToString(" · ")
    val hdr =
      hdrLabel(v.hdrFormat)?.let { label ->
        v.maxCLL.clean()?.let { "$label · MaxCLL $it" } ?: label
      }

    return listOfNotNull(
      resolution?.let { InfoField(context.getString(R.string.media_info_resolution), it) },
      frameRate?.let { InfoField(context.getString(R.string.media_info_frame_rate), it) },
      v.bitRate.clean()?.let { InfoField(context.getString(R.string.media_info_bitrate), it) },
      v.formatProfile.clean()?.let { InfoField(context.getString(R.string.media_info_profile), it) },
      bitDepth.ifBlank { null }?.let { InfoField(context.getString(R.string.media_info_bit_depth), it) },
      v.colorSpace.clean()?.let { InfoField(context.getString(R.string.media_info_color_space), it) },
      hdr?.let { InfoField(context.getString(R.string.media_info_hdr), it) },
      v.streamSize.clean()?.let { InfoField(context.getString(R.string.media_info_stream_size), it) },
    )
  }

  private fun audioRow(context: Context, a: MediaInfoOps.AudioStreamInfo): TrackRow {
    val headline = a.language.clean() ?: context.getString(R.string.media_info_unknown_language)
    val supporting =
      listOfNotNull(
        a.format.clean(),
        channelLabel(context, a.channels),
        a.samplingRate.clean(),
        a.bitRate.clean(),
      ).joinToString(" · ")
    val tags =
      buildList {
        if (isYes(a.defaultStream)) add(TrackTag.Default)
        if (isYes(a.forcedStream)) add(TrackTag.Forced)
      }
    val title = a.title.clean()
    return TrackRow(
      headline = headline,
      supporting = supporting,
      title = title,
      tags = tags,
      copyText = listOfNotNull(headline, title, supporting.ifBlank { null }).joinToString(" · "),
    )
  }

  private fun subtitleRow(context: Context, t: MediaInfoOps.TextStreamInfo): TrackRow {
    val headline = t.language.clean() ?: context.getString(R.string.media_info_unknown_language)
    val format = t.format.clean()
    val supporting = listOfNotNull(format, t.codecIdInfo.clean()?.takeIf { it != format }).joinToString(" · ")
    val tags =
      buildList {
        if (isYes(t.defaultStream)) add(TrackTag.Default)
        if (isYes(t.forcedStream)) add(TrackTag.Forced)
        if (isImageSubtitle(t)) add(TrackTag.ImageBased)
      }
    val title = t.title.clean()
    return TrackRow(
      headline = headline,
      supporting = supporting,
      title = title,
      tags = tags,
      copyText = listOfNotNull(headline, title, supporting.ifBlank { null }).joinToString(" · "),
    )
  }

  private fun fileFields(
    context: Context,
    fileName: String,
    g: MediaInfoOps.GeneralInfo,
  ): List<InfoField> {
    val container = listOfNotNull(g.format.clean(), g.formatVersion.clean()).joinToString(" ")
    return listOfNotNull(
      InfoField(context.getString(R.string.media_info_file_name), fileName),
      container.ifBlank { null }?.let { InfoField(context.getString(R.string.media_info_container), it) },
      g.duration.clean()?.let { InfoField(context.getString(R.string.media_info_duration), it) },
      g.fileSize.clean()?.let { InfoField(context.getString(R.string.media_info_size), it) },
      g.overallBitRate.clean()?.let { InfoField(context.getString(R.string.media_info_overall_bitrate), it) },
      g.encodedDate.clean()?.let { InfoField(context.getString(R.string.media_info_encoded_date), it) },
      g.writingApplication.clean()?.let { InfoField(context.getString(R.string.media_info_writing_app), it) },
      g.writingLibrary.clean()?.let { InfoField(context.getString(R.string.media_info_writing_library), it) },
      g.completeName.clean()?.let { InfoField(context.getString(R.string.media_info_location), it) },
    )
  }

  /** Answer from the same hardware check the player's decoder sheet uses. */
  private fun decoderVerdict(context: Context, v: MediaInfoOps.VideoStreamInfo): DecoderVerdict? {
    val codec = mpvCodecName(v.format) ?: return null
    val profile = v.formatProfile.clean()?.substringBefore('@')?.trim()
    val width = digits(v.width)
    val height = digits(v.height)
    val codecLabel = v.format.clean() ?: codec
    return when (val result = HardwareDecoderSupport.check(codec, profile, width, height)) {
      HardwareDecoderSupport.Result.Available -> DecoderVerdict.Hardware
      HardwareDecoderSupport.Result.Unknown -> null
      is HardwareDecoderSupport.Result.Unavailable ->
        DecoderVerdict.Software(
          when (result.reason) {
            HardwareDecoderSupport.Reason.NoHardwareDecoder ->
              context.getString(R.string.decoder_reason_no_hw, codecLabel)
            HardwareDecoderSupport.Reason.ProfileNotSupported ->
              context.getString(R.string.decoder_reason_profile, codecLabel, profile.orEmpty())
            HardwareDecoderSupport.Reason.ResolutionTooHigh ->
              context.getString(R.string.decoder_reason_resolution, codecLabel, width, height)
          },
        )
    }
  }

  private fun summary(
    context: Context,
    title: String,
    info: MediaInfoOps.MediaInfoData,
    audioTracks: List<TrackRow>,
    subtitleTracks: List<TrackRow>,
  ): String =
    buildString {
      appendLine(title)
      info.videoStreams.forEach { v ->
        val parts =
          listOfNotNull(
            listOfNotNull(v.format.clean(), v.formatProfile.clean()).joinToString(" ").ifBlank { null },
            if (digits(v.width) > 0) "${digits(v.width)}×${digits(v.height)}" else null,
            v.frameRate.clean(),
            v.bitDepth.clean(),
            hdrLabel(v.hdrFormat),
            v.bitRate.clean(),
          )
        appendLine("${context.getString(R.string.media_info_section_video)}: ${parts.joinToString(" · ")}")
      }
      audioTracks.forEachIndexed { i, track ->
        appendLine("${context.getString(R.string.media_info_section_audio)} ${i + 1}: ${track.copyText}")
      }
      if (subtitleTracks.isNotEmpty()) {
        val subs =
          subtitleTracks.joinToString(", ") { track ->
            track.supporting.ifBlank { null }?.let { "${track.headline} ($it)" } ?: track.headline
          }
        appendLine("${context.getString(R.string.media_info_section_subtitles)}: $subs")
      }
      val file =
        listOfNotNull(
          info.general.format.clean(),
          info.general.fileSize.clean(),
          info.general.duration.clean()?.let(::shortDuration),
          info.general.overallBitRate.clean(),
        )
      if (file.isNotEmpty()) {
        append("${context.getString(R.string.media_info_section_file)}: ${file.joinToString(" · ")}")
      }
    }.trimEnd()

  /** Splits MediaInfo's text report ("Section" lines followed by "Key : Value" lines). */
  fun parseReport(text: String): List<ReportSection> {
    val sections = mutableListOf<ReportSection>()
    var currentName: String? = null
    val currentProps = mutableListOf<InfoField>()

    fun flush() {
      val name = currentName
      if (name != null && currentProps.isNotEmpty()) sections.add(ReportSection(name, currentProps.toList()))
      currentProps.clear()
    }

    text.lines().forEach { line ->
      val trimmed = line.trim()
      when {
        trimmed.isEmpty() -> Unit
        !line.startsWith(" ") && !line.contains(":") -> {
          flush()
          currentName = trimmed
        }
        line.contains(":") -> {
          val parts = line.split(":", limit = 2)
          val key = parts[0].trim()
          val value = parts.getOrNull(1)?.trim().orEmpty()
          if (key.isNotEmpty() && value.isNotEmpty()) currentProps.add(InfoField(key, value))
        }
      }
    }
    flush()
    return sections
  }

  // ── Small helpers ─────────────────────────────────────────────────────────

  private val FPS_SUFFIX = Regex("""\s*fps\s*$""", RegexOption.IGNORE_CASE)

  /** MediaInfo returns "" for missing values; older code also used "---". */
  private fun String.clean(): String? = trim().takeIf { it.isNotEmpty() && it != "---" }

  /** "1 920 pixels" → 1920 */
  private fun digits(value: String): Int = value.filter { it.isDigit() }.toIntOrNull() ?: 0

  private fun isYes(value: String): Boolean = value.trim().equals("Yes", ignoreCase = true)

  /** "00:23:40.123" → "23:40", "01:02:03.000" → "1:02:03" */
  private fun shortDuration(value: String): String {
    val noMillis = value.substringBefore('.')
    val parts = noMillis.split(':')
    if (parts.size != 3) return noMillis
    val hours = parts[0].toIntOrNull() ?: return noMillis
    return if (hours == 0) "${parts[1]}:${parts[2]}" else "$hours:${parts[1]}:${parts[2]}"
  }

  /** Uses the long side, so portrait videos (1080×1920) are labelled 1080p, not 1440p. */
  private fun resolutionLabel(width: Int, height: Int): String? {
    if (width <= 0 || height <= 0) return null
    val long = maxOf(width, height)
    val short = minOf(width, height)
    return when {
      long >= 7600 -> "8K"
      long >= 3800 -> "4K"
      long >= 2500 -> "1440p"
      long >= 1900 -> "1080p"
      long >= 1260 -> "720p"
      else -> "${short}p"
    }
  }

  private fun hdrLabel(hdrFormat: String): String? {
    val value = hdrFormat.clean() ?: return null
    return when {
      value.contains("Dolby Vision", ignoreCase = true) -> "Dolby Vision"
      value.contains("HDR10+", ignoreCase = true) || value.contains("2094", ignoreCase = true) -> "HDR10+"
      value.contains("HLG", ignoreCase = true) -> "HLG"
      value.contains("2086", ignoreCase = true) || value.contains("HDR10", ignoreCase = true) -> "HDR10"
      else -> value.substringBefore(',').trim()
    }
  }

  /** "2 channels" → "Stereo", "6 channels" → "5.1" */
  private fun channelLabel(context: Context, channels: String): String? {
    val count = digits(channels)
    return when (count) {
      0 -> null
      1 -> context.getString(R.string.media_info_channels_mono)
      2 -> context.getString(R.string.media_info_channels_stereo)
      6 -> "5.1"
      8 -> "7.1"
      else -> context.getString(R.string.media_info_channels_n, count)
    }
  }

  private fun isImageSubtitle(t: MediaInfoOps.TextStreamInfo): Boolean {
    val id = "${t.format} ${t.codecId}".uppercase()
    return listOf("PGS", "VOBSUB", "HDMV", "DVB", "S_IMAGE").any { it in id }
  }

  /** MediaInfo format name → the mpv codec name HardwareDecoderSupport expects. */
  private fun mpvCodecName(format: String): String? =
    when (format.trim().lowercase()) {
      "avc" -> "h264"
      "hevc" -> "hevc"
      "av1" -> "av1"
      "vp9" -> "vp9"
      "vp8" -> "vp8"
      "mpeg video" -> "mpeg2video"
      "mpeg-4 visual" -> "mpeg4"
      "h.263" -> "h263"
      else -> null
    }
}
